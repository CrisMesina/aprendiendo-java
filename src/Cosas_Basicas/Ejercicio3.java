package Cosas_Basicas;
public class Ejercicio3 {

    public static void main(String[] args){

        int numero = 10;

        System.out.println("VALOR INICIAL: " + numero);

        numero += 5;

        System.out.println("DESPUES DE SUMAR 5: " + numero);

        numero -= 3;

        System.out.println("DESPUES DE RESTAR 3:" + numero);

        numero *= 2;

        System.out.println("DESPUES DE MULTIPLICAR POR 2: " + numero);

        numero /= 4;

        System.out.println("DESPUES DE DIVIDIR POR 4: " + numero);

    }

}
